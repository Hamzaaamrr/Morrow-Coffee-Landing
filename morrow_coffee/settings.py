DEBUG = os.environ.get("DJANGO_DEBUG", "1") == "1"
SECRET_KEY = os.environ.get("DJANGO_SECRET_KEY")
if not SECRET_KEY and DEBUG:
    local_secret_file = BASE_DIR / ".django_secret_key"
    if local_secret_file.exists():
        SECRET_KEY = local_secret_file.read_text(encoding="utf-8").strip()
    else:
        SECRET_KEY = get_random_secret_key()
        local_secret_file.write_text(SECRET_KEY, encoding="utf-8")
if not SECRET_KEY:
    raise RuntimeError("Set DJANGO_SECRET_KEY in the environment when DJANGO_DEBUG=0.")

